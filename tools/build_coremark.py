#!/usr/bin/env python3
"""Build unchanged official CoreMark kernels for this RV32IM/MMIO platform."""
import argparse
import hashlib
import json
from pathlib import Path
import subprocess

ROOT=Path(__file__).resolve().parents[1]
UPSTREAM=ROOT/'benchmarks/coremark/upstream'

def build(kind,iterations):
    manifest=json.loads((ROOT/'benchmarks/coremark/UPSTREAM.json').read_text())
    for name,digest in manifest['sha256'].items():
        if hashlib.sha256((UPSTREAM/name).read_bytes()).hexdigest()!=digest:
            raise ValueError(f'upstream file changed: {name}')
    suffix='auto' if iterations==0 else str(iterations)
    name=f'coremark_{kind}_{suffix}'
    directory=ROOT/'build_perf'/name
    directory.mkdir(parents=True,exist_ok=True)
    flags='-march=rv32im -mabi=ilp32 -O2 -ffreestanding -nostdlib -mno-relax -msmall-data-limit=0'
    config=f'''/* Generated by tools/build_coremark.py. */
#define ITERATIONS {iterations}
#define PERFORMANCE_RUN {int(kind=='performance')}
#define VALIDATION_RUN {int(kind=='validation')}
#define TOTAL_DATA_SIZE 2000
#define COMPILER_FLAGS "{flags}; static; ITERATIONS={iterations}; {kind}"
'''
    (directory/'coremark_build.h').write_bytes(config.encode())
    extra=' '.join('benchmarks/coremark/upstream/'+name for name in
                   ('core_list_join.c','core_matrix.c','core_state.c','core_util.c'))
    extra+=' benchmarks/coremark/port/core_portme.c benchmarks/coremark/port/ee_printf.c'
    command=['make','mem','PERF=1',f'OUT_NAME={name}',
             'SRC=benchmarks/coremark/upstream/core_main.c',f'EXTRA_SRCS={extra}',
             f'APP_DEFINES=-Ibenchmarks/coremark/port -Ibenchmarks/coremark/upstream -Ibuild_perf/{name}',
             f'MEM_OUT=build_perf/{name}.mem','LDLIBS=-lgcc']
    subprocess.run(command,cwd=ROOT,check=True)
    image=ROOT/f'build_perf/{name}.mem'
    meta=Path(str(image)+'.json')
    record=json.loads(meta.read_text())
    record['ldlibs']='-lgcc'
    record['benchmark']={'name':'CoreMark','upstream_commit':manifest['commit'],
                         'iterations':iterations,'run_kind':kind,'data_bytes':2000,
                         'timer':'microseconds from live PMU high-low-high read',
                         'note':'Short runs validate CRC only; reportable timing requires >=10 seconds and both required seed runs.'}
    meta.write_text(json.dumps(record,indent=2)+'\n')
    print(f'COREMARK IMAGE: {image}',flush=True)
    return image

def main():
    ap=argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--iterations',type=int,default=0,help='0=official auto calibration; 1=short RTL CRC validation')
    ap.add_argument('--kind',choices=['performance','validation','both'],default='both')
    args=ap.parse_args()
    if args.iterations<0 or args.iterations>0x7fffffff:
        ap.error('iterations out of range')
    for kind in (['performance','validation'] if args.kind=='both' else [args.kind]):
        build(kind,args.iterations)
    return 0

if __name__=='__main__':
    raise SystemExit(main())
